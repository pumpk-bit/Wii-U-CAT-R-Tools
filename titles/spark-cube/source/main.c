/*
 * SparkCube - minimal GX2 spinning cube linked with gx2spark.a.
 *
 * The smallest real GX2 title that registers the SPARK capture library on
 * the CAT-R (patched 1000400A gx2.rpl). Draws one indexed, vertex-colored
 * cube on TV and GamePad and writes SPARK frame captures over Wi-Fi PCFS.
 *
 * Controls (GamePad):
 *   A     capture the next frame to CAPTURE_PATH (GX2DebugCaptureFrame)
 *   HOME  normal HOME menu / exit through ProcUI (handled by DEMO)
 */
#include <cafe/demo.h>
#include <cafe/gx2.h>
#include <cafe/os.h>
#include <cafe/vpad.h>

#include <math.h>
#include <stddef.h>
#include <stdio.h>
#include <string.h>

/* Generated by scripts/Build.ps1 from shaders/spark_cube.{vsh,psh}:
 * the compiled .gsh file as a byte array (g_spark_cube_gsh). */
#include "spark_cube_gsh.h"

#define SPARK_CUBE_VERSION "v0.18"

void dbg_try_start(void);   /* source/dbg_try.c */

/*
 * Where the .4mp goes: <pcfs-root>\data\save\spark\spark_cube.4mp on the PC.
 *
 * gx2spark writes through /vol/spark (/dev/hfio01, i.e. PCFS) and converts
 * the name with WinToCafePath: "/cygdrive/X" becomes /vol/spark/X. pcfsserver
 * only serves paths under its root, through the %..._EMU_DIR keywords, so
 * DOS ("C:\...") and UNC ("\\host\share\...") names fail to open, and bare
 * names need CAFE_ROOT env vars a CAT-R doesn't have. The spark folder must
 * already exist. Each capture overwrites the previous one.
 *
 * If the open fails, the capture stays pending and GX2 retries it every
 * frame (with swap interval 0) until it succeeds.
 */
#define CAPTURE_PATH "/cygdrive/%SAVE_EMU_DIR/spark/spark_cube.4mp"

typedef struct
{
    f32 pos[3];
    f32 color[3];
} Vertex;

/* 24 vertices: 4 per face so each face gets a flat color. */
static const Vertex k_cube_vertices[24] = {
    /* +Z front: red */
    {{-1, -1,  1}, {0.95f, 0.25f, 0.25f}}, {{ 1, -1,  1}, {0.95f, 0.25f, 0.25f}},
    {{ 1,  1,  1}, {0.95f, 0.25f, 0.25f}}, {{-1,  1,  1}, {0.95f, 0.25f, 0.25f}},
    /* -Z back: green */
    {{ 1, -1, -1}, {0.25f, 0.85f, 0.35f}}, {{-1, -1, -1}, {0.25f, 0.85f, 0.35f}},
    {{-1,  1, -1}, {0.25f, 0.85f, 0.35f}}, {{ 1,  1, -1}, {0.25f, 0.85f, 0.35f}},
    /* +X right: blue */
    {{ 1, -1,  1}, {0.25f, 0.45f, 0.95f}}, {{ 1, -1, -1}, {0.25f, 0.45f, 0.95f}},
    {{ 1,  1, -1}, {0.25f, 0.45f, 0.95f}}, {{ 1,  1,  1}, {0.25f, 0.45f, 0.95f}},
    /* -X left: yellow */
    {{-1, -1, -1}, {0.95f, 0.85f, 0.25f}}, {{-1, -1,  1}, {0.95f, 0.85f, 0.25f}},
    {{-1,  1,  1}, {0.95f, 0.85f, 0.25f}}, {{-1,  1, -1}, {0.95f, 0.85f, 0.25f}},
    /* +Y top: cyan */
    {{-1,  1,  1}, {0.25f, 0.90f, 0.95f}}, {{ 1,  1,  1}, {0.25f, 0.90f, 0.95f}},
    {{ 1,  1, -1}, {0.25f, 0.90f, 0.95f}}, {{-1,  1, -1}, {0.25f, 0.90f, 0.95f}},
    /* -Y bottom: magenta */
    {{-1, -1, -1}, {0.90f, 0.30f, 0.90f}}, {{ 1, -1, -1}, {0.90f, 0.30f, 0.90f}},
    {{ 1, -1,  1}, {0.90f, 0.30f, 0.90f}}, {{-1, -1,  1}, {0.90f, 0.30f, 0.90f}},
};

#define CUBE_INDEX_COUNT 36

static DEMOGfxShader g_shader;
static Vertex *g_vertex_buffer = NULL;
static u16 *g_index_buffer = NULL;
static u32 g_mvp_location = 0;

static u32 g_frame = 0;
static u32 g_capture_requests = 0;

/* ------------------------------------------------------------------ */
/* Row-major 4x4 math. The shader computes dot(row_i, p).              */
/* ------------------------------------------------------------------ */

static void mat_identity(f32 m[16])
{
    memset(m, 0, 16 * sizeof(f32));
    m[0] = m[5] = m[10] = m[15] = 1.0f;
}

static void mat_mul(const f32 a[16], const f32 b[16], f32 out[16])
{
    f32 r[16];
    int i, j, k;

    for (i = 0; i < 4; i++) {
        for (j = 0; j < 4; j++) {
            f32 sum = 0.0f;
            for (k = 0; k < 4; k++) {
                sum += a[i * 4 + k] * b[k * 4 + j];
            }
            r[i * 4 + j] = sum;
        }
    }
    memcpy(out, r, sizeof(r));
}

static void mat_translate(f32 m[16], f32 x, f32 y, f32 z)
{
    mat_identity(m);
    m[3] = x;
    m[7] = y;
    m[11] = z;
}

static void mat_rotate_x(f32 m[16], f32 rad)
{
    f32 c = cosf(rad), s = sinf(rad);
    mat_identity(m);
    m[5] = c;  m[6] = -s;
    m[9] = s;  m[10] = c;
}

static void mat_rotate_y(f32 m[16], f32 rad)
{
    f32 c = cosf(rad), s = sinf(rad);
    mat_identity(m);
    m[0] = c;  m[2] = s;
    m[8] = -s; m[10] = c;
}

/* OpenGL-style perspective (clip z in -w..w). */
static void mat_perspective(f32 m[16], f32 fovy, f32 aspect, f32 n, f32 f)
{
    f32 t = 1.0f / tanf(fovy * 0.5f);
    memset(m, 0, 16 * sizeof(f32));
    m[0] = t / aspect;
    m[5] = t;
    m[10] = (f + n) / (n - f);
    m[11] = (2.0f * f * n) / (n - f);
    m[14] = -1.0f;
}

/* ------------------------------------------------------------------ */

static BOOL init_cube(void)
{
    static const u16 face[6] = {0, 1, 2, 0, 2, 3};
    int f, i;

    if (!DEMOGfxLoadShaders(&g_shader, 0, g_spark_cube_gsh)) {
        OSReport("SparkCube: DEMOGfxLoadShaders failed\n");
        return FALSE;
    }
    DEMOGfxInitShaderAttribute(&g_shader, "a_position", 0,
                               offsetof(Vertex, pos),
                               GX2_ATTRIB_FORMAT_32_32_32_FLOAT);
    DEMOGfxInitShaderAttribute(&g_shader, "a_color", 0,
                               offsetof(Vertex, color),
                               GX2_ATTRIB_FORMAT_32_32_32_FLOAT);
    DEMOGfxGetVertexShaderUniformLocation(&g_shader, "u_mvp");
    g_mvp_location = g_shader.uniformsVS.location[0];
    if (!DEMOGfxInitFetchShader(&g_shader)) {
        OSReport("SparkCube: DEMOGfxInitFetchShader failed\n");
        return FALSE;
    }

    g_vertex_buffer = (Vertex *)DEMOGfxAllocMEM2(sizeof(k_cube_vertices),
                                                 GX2_VERTEX_BUFFER_ALIGNMENT);
    g_index_buffer = (u16 *)DEMOGfxAllocMEM2(CUBE_INDEX_COUNT * sizeof(u16),
                                             GX2_INDEX_BUFFER_ALIGNMENT);
    if (g_vertex_buffer == NULL || g_index_buffer == NULL) {
        OSReport("SparkCube: buffer allocation failed\n");
        return FALSE;
    }

    memcpy(g_vertex_buffer, k_cube_vertices, sizeof(k_cube_vertices));
    for (f = 0; f < 6; f++) {
        for (i = 0; i < 6; i++) {
            g_index_buffer[f * 6 + i] = (u16)(f * 4 + face[i]);
        }
    }
    GX2Invalidate(GX2_INVALIDATE_CPU_ATTRIB_BUFFER, g_vertex_buffer,
                  sizeof(k_cube_vertices));
    DCFlushRange(g_index_buffer, CUBE_INDEX_COUNT * sizeof(u16));
    return TRUE;
}

static void free_cube(void)
{
    if (g_vertex_buffer != NULL) {
        DEMOGfxFreeMEM2(g_vertex_buffer);
        g_vertex_buffer = NULL;
    }
    if (g_index_buffer != NULL) {
        DEMOGfxFreeMEM2(g_index_buffer);
        g_index_buffer = NULL;
    }
    DEMOGfxFreeShaders(&g_shader);
}

static void draw_cube(f32 aspect)
{
    f32 proj[16], trans[16], rot_x[16], rot_y[16], model[16], mvp[16];
    f32 t = (f32)g_frame * (1.0f / 60.0f);

    mat_perspective(proj, 0.9f, aspect, 0.1f, 100.0f);
    mat_translate(trans, 0.0f, 0.0f, -5.0f);
    mat_rotate_y(rot_y, t * 1.1f);
    mat_rotate_x(rot_x, t * 0.7f);
    mat_mul(rot_y, rot_x, model);
    mat_mul(trans, model, model);
    mat_mul(proj, model, mvp);

    GX2SetShaders(&g_shader.fetchShader, g_shader.pVertexShader,
                  g_shader.pPixelShader);
    GX2SetVertexUniformReg(g_mvp_location, 16, mvp);
    GX2SetAttribBuffer(0, sizeof(k_cube_vertices), sizeof(Vertex),
                       g_vertex_buffer);
    GX2SetDepthOnlyControl(GX2_TRUE, GX2_TRUE, GX2_COMPARE_LEQUAL);
    /* No culling: depth test alone is enough, and it removes any risk of
     * the winding being read the other way round. */
    GX2SetCullOnlyControl(GX2_FRONT_FACE_CCW, GX2_FALSE, GX2_FALSE);

    /* Shows up as a comment in the SPARK command list; ignored otherwise. */
    GX2DebugTagUserString(GX2_DEBUG_TAG_COMMENT, "SparkCube draw frame %u",
                          g_frame);
    GX2DrawIndexedEx(GX2_PRIMITIVE_TRIANGLES, CUBE_INDEX_COUNT,
                     GX2_INDEX_FORMAT_U16, g_index_buffer, 0, 1);
}

static void draw_overlay(GX2ColorBuffer *target)
{
    DEMOFontSetTarget(target);
    DEMOFontSetContextState();
    DEMOFontSetColor(0.35f, 0.85f, 1.0f, 1.0f);
    DEMOFontPrintf(3.0f, 2.0f, "SPARK CUBE " SPARK_CUBE_VERSION
                   "  (gx2spark linked)");
    DEMOFontSetColor(0.82f, 0.88f, 0.94f, 1.0f);
    DEMOFontPrintf(3.0f, 3.5f, "Frame %u   A: capture (%u requested)",
                   g_frame, g_capture_requests);
    DEMOFontSetColor(0.70f, 0.80f, 0.55f, 1.0f);
    DEMOFontPrintf(3.0f, 5.0f, "%s", CAPTURE_PATH);
}

static void render_tv(void)
{
    DEMOGfxBeforeRender();
    GX2ClearColor(&DEMOColorBuffer, 0.04f, 0.05f, 0.08f, 1.0f);
    GX2ClearDepthStencilEx(&DEMODepthBuffer, 1.0f, 0, GX2_CLEAR_BOTH);
    DEMOGfxSetContextState();
    draw_cube((f32)DEMOColorBuffer.surface.width /
              (f32)DEMOColorBuffer.surface.height);
    draw_overlay(&DEMOColorBuffer);
    DEMOGfxDoneRender();
}

static void render_drc(void)
{
    DEMODRCBeforeRender();
    GX2ClearColor(&DEMODRCColorBuffer, 0.04f, 0.05f, 0.08f, 1.0f);
    GX2ClearDepthStencilEx(&DEMODRCDepthBuffer, 1.0f, 0, GX2_CLEAR_BOTH);
    DEMODRCSetContextState();
    draw_cube((f32)DEMODRCColorBuffer.surface.width /
              (f32)DEMODRCColorBuffer.surface.height);
    draw_overlay(&DEMODRCColorBuffer);
    DEMODRCDoneRender();
}

static void update_input(void)
{
    VPADStatus status;
    s32 error = VPAD_READ_ERR_NONE;

    if (VPADRead(0, &status, 1, &error) <= 0 ||
        error != VPAD_READ_ERR_NONE) {
        return;
    }
    if (status.trig & VPAD_BUTTON_A) {
        g_capture_requests++;
        OSReport("SparkCube: capture request %u at frame %u -> %s\n",
                 g_capture_requests, g_frame, CAPTURE_PATH);
        GX2DebugCaptureFrame(CAPTURE_PATH);
    }
}

int main(int argc, char **argv)
{
    OSReport("SparkCube " SPARK_CUBE_VERSION " starting\n");
    OSReport("SparkCube: consoleType=0x%08X securityLevel=%u\n",
             OSGetConsoleType(), OSGetSecurityLevel());
    /* v0.5: print the arguments so catr can check that cos launchex passes them. */
    OSReport("SparkCube: argc=%d\n", argc);
    for (int i = 0; i < argc; i++)
        OSReport("SparkCube: argv[%d]=\"%s\"\n", i, argv[i] ? argv[i] : "(null)");

    /* "dbgtry" starts coreinit's GDB stub and waits for a debugger
     * (source/dbg_try.c, plugins/dk-tcp). */
    for (int i = 1; i < argc; i++) {
        if (argv[i] && strstr(argv[i], "dbgtry")) {
            dbg_try_start();
            break;
        }
    }

    DEMOInit();
    DEMOGfxInit(argc, argv);
    DEMODRCInit(argc, argv);
    /* Not done by DEMOGfxInit. Without it every DEMOFont* call writes
     * through a NULL font instance (v0.1 crashed in DEMOFontSetColor). */
    DEMOFontInit();

    /* Must come after GX2 init. With the patched gx2.rpl this registers
     * gx2spark's interface, whose SubmitToRing forwards to TCL while no
     * capture is armed, and mounts /vol/spark (PCFS). v0.6: its "SparkCapture"
     * HIO channel opens through hio_socket.c (HIO over TCP 6100, bridged to
     * SPARK by catr hio), since coreinit's HIO stops on a headless CAT-R. If gx2 rejects the interface, GX2 logs
     * "Capture not supported in production mode". */
    OSReport("SparkCube: GX2DebugCaptureInit begin\n");
    GX2DebugCaptureInit(NULL);
    OSReport("SparkCube: GX2DebugCaptureInit returned\n");

    if (init_cube()) {
        OSReport("SparkCube: cube ready, entering main loop\n");
        while (DEMOIsRunning()) {
            update_input();
            render_tv();
            render_drc();
            g_frame++;
            if ((g_frame % 600) == 0) {
                OSReport("SparkCube: alive, frame %u\n", g_frame);
            }
        }
    } else {
        /* Keep ProcUI happy so the title can still exit normally. */
        while (DEMOIsRunning()) {
            OSSleepMilliseconds(16);
        }
    }

    free_cube();
    DEMOFontShutdown();
    DEMODRCShutdown();
    DEMOGfxShutdown();
    DEMOShutdown();
    return 0;
}
