[CmdletBinding()]
param(
    # The Cafe SDK 2.12.13 and GHS v5.3.27 folders; default to CAFE_ROOT and GHS_ROOT.
    [string]$CafeRoot = $env:CAFE_ROOT,
    [string]$GhsRoot = $env:GHS_ROOT,
    [string]$DevkitPro = 'C:\devkitPro',
    [ValidateSet('DEBUG', 'NDEBUG', 'FDEBUG')]
    [string]$BuildType = 'NDEBUG',
    # Defaults to SparkCube-vNN, from <title_version> in metadata\code\app.xml.
    [string]$OutputName,
    [switch]$SkipPackage
)

# Builds SparkCube: compiles the GLSL shaders with gshCompile, embeds the
# .gsh as a C array, builds the RPX with the Cafe SDK makefiles (GHS), and
# packages a .wumad plus an SD install image with makecfmaster.
# Keep this script ASCII-only (Windows PowerShell 5.1 reads it as ANSI).

$ErrorActionPreference = 'Stop'

# CAFE_ROOT and GHS_ROOT may be in Windows form (C:\x) or MSYS/Cygwin form (/c/x, /cygdrive/c/x).
function ConvertTo-WindowsPath([string]$Path) {
    if ($Path -match '^(?:/cygdrive)?/([A-Za-z])/(.*)$') {
        return "$($Matches[1].ToUpperInvariant()):\$($Matches[2].Replace('/', '\'))"
    }
    return $Path
}
$CafeRoot = ConvertTo-WindowsPath $CafeRoot
if (-not $CafeRoot) { throw 'Pass -CafeRoot (the Cafe SDK 2.12.13 folder), or set CAFE_ROOT.' }
$GhsRoot = ConvertTo-WindowsPath $GhsRoot
if (-not $GhsRoot) { throw 'Pass -GhsRoot (the GHS v5.3.27 folder), or set GHS_ROOT.' }

$projectRoot = Split-Path -Parent $PSScriptRoot
$make = Join-Path $DevkitPro 'msys2\usr\bin\make.exe'
$gshCompile = Join-Path $CafeRoot 'system\bin\win64\gshCompile.exe'

# The SDK's makefiles can't handle spaces in paths.
foreach ($folder in @($CafeRoot, $GhsRoot, $projectRoot)) {
    if ($folder -match '\s') { throw "The path has a space in it, which the Cafe SDK's makefiles can't handle: $folder" }
}
$titleId = '0005000010c0be00'

# metadata\code\app.xml is the one place the title version is set; meta.xml
# and the output name follow it. Keep SPARK_CUBE_VERSION in source\main.c in
# step with it.
[xml]$appXml = Get-Content -Raw -LiteralPath (Join-Path $projectRoot 'metadata\code\app.xml')
$titleVersion = [Convert]::ToInt32($appXml.app.title_version.'#text', 16)
if (-not $OutputName) {
    $OutputName = 'SparkCube-v{0:D2}' -f $titleVersion
}

foreach ($required in @($CafeRoot, (Join-Path $GhsRoot 'ccppc.exe'), $make, $gshCompile)) {
    if (-not (Test-Path -LiteralPath $required)) {
        throw "Required tool or folder not found: $required"
    }
}

# --- 1. Shaders -> source/spark_cube_gsh.h -------------------------------
$shaderDir = Join-Path $projectRoot 'shaders'
$genDir = Join-Path $projectRoot 'build\gen'
New-Item -ItemType Directory -Force -Path $genDir | Out-Null
$gshPath = Join-Path $genDir 'spark_cube.gsh'

# Default gshCompile output keeps SPARK shader debug info (a 16-byte hash per
# shader plus a symbol file under %LOCALAPPDATA%\Temp\Nintendo\Cafe\ShaderSymbols),
# which SPARK uses to show shader source.
& $gshCompile -v (Join-Path $shaderDir 'spark_cube.vsh') -p (Join-Path $shaderDir 'spark_cube.psh') -o $gshPath
if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $gshPath)) {
    throw "gshCompile failed with exit code $LASTEXITCODE"
}

$bytes = [System.IO.File]::ReadAllBytes($gshPath)
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/* Generated by scripts/Build.ps1 from shaders/spark_cube.{vsh,psh}. Do not edit. */')
[void]$sb.AppendLine('#ifndef SPARK_CUBE_GSH_H')
[void]$sb.AppendLine('#define SPARK_CUBE_GSH_H')
[void]$sb.AppendLine("#define SPARK_CUBE_GSH_SIZE $($bytes.Length)u")
[void]$sb.AppendLine('static const u8 g_spark_cube_gsh[SPARK_CUBE_GSH_SIZE] __attribute__((aligned(256))) = {')
for ($i = 0; $i -lt $bytes.Length; $i += 16) {
    $end = [Math]::Min($i + 16, $bytes.Length)
    $parts = for ($j = $i; $j -lt $end; $j++) { '0x{0:x2}' -f $bytes[$j] }
    [void]$sb.AppendLine('    ' + ($parts -join ',') + ',')
}
[void]$sb.AppendLine('};')
[void]$sb.AppendLine('#endif')
$utf8NoBom = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllText((Join-Path $projectRoot 'source\spark_cube_gsh.h'), $sb.ToString(), $utf8NoBom)
Write-Host "Embedded $($bytes.Length)-byte shader file"

# --- 1b. gx2spark commsManager.o with HIO renamed ----------------------------
# source/hio_socket.c implements HIO over sockets as HSKInit, HSKOpenEx, ...
# coreinit's import library defines every HIO function in one member, so they
# can't be overridden by name. Take gx2spark's commsManager.o (the only member
# that calls HIO) and rename its five HIO symbol names in place in the string
# table, same length (HIO -> HSK), so no other byte of the GHS object changes.
# The Makefile links the copy ahead of gx2spark.a. The SDK archive is not
# modified.
$devkitAr = Join-Path $DevkitPro 'devkitPPC\bin\powerpc-eabi-ar.exe'
$gx2sparkA = Join-Path $CafeRoot "system\lib\ghs\cafe\$BuildType\gx2spark.a"
$commsDir = Join-Path $projectRoot "build\obj\$BuildType\gx2spark"
foreach ($required in @($devkitAr, $gx2sparkA)) {
    if (-not (Test-Path -LiteralPath $required)) { throw "Missing $required" }
}
# The SDK's generated .dep files come out malformed on the second build
# ("missing separator"), so always build from clean objects; it takes seconds.
$objDir = Join-Path $projectRoot "build\obj\$BuildType"
if (Test-Path -LiteralPath $objDir) {
    Remove-Item -LiteralPath $objDir -Recurse -Force
}
New-Item -ItemType Directory -Force -Path $commsDir | Out-Null
Push-Location $commsDir
try {
    & $devkitAr x $gx2sparkA commsManager.o
    if ($LASTEXITCODE -ne 0) { throw "ar x commsManager.o failed with exit code $LASTEXITCODE" }
} finally {
    Pop-Location
}
$commsSource = Join-Path $commsDir 'commsManager.o'
$obj = [System.IO.File]::ReadAllBytes($commsSource)
$latin1 = [System.Text.Encoding]::GetEncoding(28591)
$text = $latin1.GetString($obj)
foreach ($name in @('Init', 'OpenEx', 'Read', 'Write', 'Close')) {
    $from = "`0HIO$name`0"
    $hits = [regex]::Matches($text, [regex]::Escape($from))
    if ($hits.Count -ne 1) {
        throw "commsManager.o: expected one 'HIO$name' symbol name, found $($hits.Count)"
    }
    $at = $hits[0].Index + 2   # the 'I' of HIO
    $obj[$at] = [byte][char]'S'
    $obj[$at + 1] = [byte][char]'K'
}
$patched = $latin1.GetString($obj)
if ([regex]::IsMatch($patched, "`0HIO(Init|OpenEx|Read|Write|Close|ReadAsyncEx|WriteAsyncEx|Shutdown)`0")) {
    throw 'commsManager.o still names a HIO function'
}
[System.IO.File]::WriteAllBytes((Join-Path $commsDir 'commsManager_hio.o'), $obj)
Remove-Item -LiteralPath $commsSource
Write-Host 'Wrote commsManager_hio.o (HIO -> HSK)'

# --- 2. RPX ------------------------------------------------------------------
function ConvertTo-MsysDrivePath([string]$Path) {
    $resolved = [System.IO.Path]::GetFullPath($Path)
    if ($resolved -notmatch '^([A-Za-z]):\\(.*)$') {
        throw "Expected a drive-qualified Windows path: $resolved"
    }
    return "/$($Matches[1].ToLowerInvariant())/$($Matches[2].Replace('\', '/'))"
}

$env:CAFE_ROOT = ConvertTo-MsysDrivePath $CafeRoot
$env:GHS_ROOT = ConvertTo-MsysDrivePath $GhsRoot
$env:CAFE_GHS_VERSION = 'v5.3.27'
$env:CAFE_GHS_SUPPORTS_MAKERPL_DBG_SOURCE_ROOT = 'TRUE'
$env:CAFE_GHS_TLS_AVAILABLE = 'TRUE'
$env:CAFE_SDK = 'TRUE'
$env:TOOLCHAIN = 'ghs'
$env:USE_GHS = '1'
$env:PLATFORM = 'cafe'
# The build's own temporary folder: the user's may have a space in its path.
$tmpFolder = Join-Path $projectRoot 'build\tmp'
New-Item -ItemType Directory -Force -Path $tmpFolder | Out-Null
$env:TMP = ConvertTo-MsysDrivePath $tmpFolder

# make prints a harmless "did not update peer target ... .rpl" warning on
# stderr; only the exit code decides success.
$ErrorActionPreference = 'Continue'
& $make -C (ConvertTo-MsysDrivePath $projectRoot) "BUILD_TYPE=$BuildType" install 2>&1 | ForEach-Object { "$_" }
$makeExit = $LASTEXITCODE
$ErrorActionPreference = 'Stop'
if ($makeExit -ne 0) {
    throw "Cafe build failed with exit code $makeExit"
}

$builtRpx = Join-Path $projectRoot "build\$BuildType\spark_cube.rpx"
if (-not (Test-Path -LiteralPath $builtRpx)) {
    throw "Built RPX not found: $builtRpx"
}
Write-Host "Built $builtRpx"
if ($SkipPackage) {
    return
}

# --- 3. Master folder (code / content / meta) ---------------------------------
$masterRoot = Join-Path $projectRoot 'master'
$codeRoot = Join-Path $masterRoot 'code'
$contentRoot = Join-Path $masterRoot 'content'
$metaRoot = Join-Path $masterRoot 'meta'
$tempRoot = Join-Path (Join-Path $projectRoot 'master-temp') (Get-Date -Format 'yyyyMMdd-HHmmss')
$outputRoot = Join-Path $projectRoot 'Install'
New-Item -ItemType Directory -Force -Path $codeRoot, $contentRoot, $metaRoot, $tempRoot, $outputRoot | Out-Null

Copy-Item -LiteralPath $builtRpx -Destination (Join-Path $codeRoot 'spark_cube.rpx') -Force
Copy-Item -LiteralPath (Join-Path $projectRoot 'metadata\code\app.xml') -Destination $codeRoot -Force
Copy-Item -LiteralPath (Join-Path $projectRoot 'metadata\code\cos.xml') -Destination $codeRoot -Force

# DEMOGfxInit loads the DEMO font from /vol/content/assets/...; it is required.
$fontShaderSource = Join-Path $CafeRoot 'data\disc\content\assets\shaders\lib_demo\cafe\demoFont.gsh'
$fontShaderTarget = Join-Path $contentRoot 'assets\shaders\lib_demo\cafe\demoFont.gsh'
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $fontShaderTarget) | Out-Null
Copy-Item -LiteralPath $fontShaderSource -Destination $fontShaderTarget -Force

# Boot images: reuse the SDK's System Config Tool assets (as the Recovery Menu does).
$sdkMetaRoot = Join-Path $CafeRoot 'data\mlc\sys\title\00050010\1f700500\meta'
foreach ($asset in 'bootDrcTex.tga','bootLogoTex.tga','bootMovie.h264','bootTvTex.tga','iconTex.tga') {
    Copy-Item -LiteralPath (Join-Path $sdkMetaRoot $asset) -Destination $metaRoot -Force
}

$metaText = Get-Content -Raw -Encoding UTF8 -LiteralPath (Join-Path $CafeRoot 'system\bin\ghs\cafe\boot\meta_default.xml')
$metaText = $metaText.Replace('0005000011000000', $titleId.ToUpperInvariant())
$metaText = $metaText.Replace('<group_id type="hexBinary" length="4">00010000</group_id>', '<group_id type="hexBinary" length="4">0000C0BE</group_id>')
# Must match the OS whose gx2.rpl carries the SPARK gate patch.
$metaText = $metaText.Replace('000500101000800A', '000500101000400A')
$metaText = $metaText.Replace('<title_version type="unsignedInt" length="4">0</title_version>', "<title_version type=`"unsignedInt`" length=`"4`">$titleVersion</title_version>")
$metaText = $metaText.Replace('<e_manual type="unsignedInt" length="4">1</e_manual>', '<e_manual type="unsignedInt" length="4">0</e_manual>')
$metaText = $metaText.Replace('<region type="hexBinary" length="4">00000002</region>', '<region type="hexBinary" length="4">FFFFFFFF</region>')
$metaText = $metaText.Replace('Long Title Name (EN)', 'Spark Cube')
$metaText = $metaText.Replace('Short Title Name (EN)', 'Spark Cube')
$metaText = $metaText.Replace('Publisher Name (EN)', 'CAT-R homebrew')
[System.IO.File]::WriteAllText((Join-Path $metaRoot 'meta.xml'), $metaText, $utf8NoBom)

# --- 4. wumad + SD install image -----------------------------------------------
$masteringRoot = Join-Path $CafeRoot 'system\bin\tool\mastering'
$makeCfMaster = Join-Path $masteringRoot 'makecfmaster.exe'
$env:CAFE_ROOT = $CafeRoot
$env:CAFE_TEMP = $tempRoot
$env:CAFE_DATA_DIR = Join-Path $projectRoot 'data'
$env:CAFE_CONTENT_DIR = $contentRoot
$env:CAFE_META_DIR = $metaRoot
$env:CAFE_SAVE_DIR = Join-Path $CafeRoot 'save'
$env:CAFE_SLC_DIR = Join-Path $CafeRoot 'data\slc'
$env:CAFE_MLC_DIR = Join-Path $CafeRoot 'data\mlc'
$env:PATH = "$masteringRoot;$(Join-Path $CafeRoot 'system\bin\tool');$env:PATH"

$wumadBase = Join-Path $projectRoot $OutputName
Push-Location $CafeRoot
try {
    & $makeCfMaster archive -r (Join-Path $codeRoot 'spark_cube.rpx') -o $wumadBase -w $tempRoot
    if ($LASTEXITCODE -ne 0) {
        throw "Master archive creation failed with exit code $LASTEXITCODE"
    }
    & $makeCfMaster installimage -i "$wumadBase.wumad" -o $outputRoot -w $tempRoot
    if ($LASTEXITCODE -ne 0) {
        throw "Install image creation failed with exit code $LASTEXITCODE"
    }
} finally {
    Pop-Location
}

# makecfmaster's scratch folder; kept above only if packaging failed.
Remove-Item -LiteralPath $tempRoot -Recurse -Force -ErrorAction SilentlyContinue

Write-Host "Created $wumadBase.wumad"
Write-Host "Created install image under $outputRoot"
